create or replace function public.touch_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists application_notes_touch on public.application_notes;
create trigger application_notes_touch before update on public.application_notes for each row execute function public.touch_updated_at();
drop trigger if exists user_documents_touch on public.user_documents;
create trigger user_documents_touch before update on public.user_documents for each row execute function public.touch_updated_at();
drop trigger if exists saved_searches_touch on public.saved_searches;
create trigger saved_searches_touch before update on public.saved_searches for each row execute function public.touch_updated_at();

create or replace function public.get_user_backend_snapshot()
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare uid uuid := (select auth.uid());
begin
  if uid is null then raise exception 'not_authenticated'; end if;
  return jsonb_build_object(
    'profile', (select to_jsonb(p) from public.profiles p where p.id = uid),
    'student_profile', (select to_jsonb(sp) from public.student_profiles sp where sp.user_id = uid),
    'wassce_results', coalesce((select jsonb_agg(to_jsonb(w) order by w.subject) from public.wassce_results w where w.user_id = uid), '[]'::jsonb),
    'saved_items', coalesce((select jsonb_agg(to_jsonb(s) order by s.created_at desc) from public.saved_items s where s.user_id = uid), '[]'::jsonb),
    'match_preferences', (select to_jsonb(m) from public.match_preferences m where m.user_id = uid),
    'notification_preferences', (select to_jsonb(n) from public.notification_preferences n where n.user_id = uid)
  );
end;
$$;

revoke all on function public.get_user_backend_snapshot() from public;
grant execute on function public.get_user_backend_snapshot() to authenticated;

